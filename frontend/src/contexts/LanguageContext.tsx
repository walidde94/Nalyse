const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: ReactNode }> = ({ children }) => {
    const [language, setLanguageState] = useState<Language>(() => {
        const stored = localStorage.getItem('language') as Language;
        if (stored) return stored;
        return 'de'; // Set default to German as requested
    });

    const setLanguage = (lang: Language) => {
        setLanguageState(lang);
        localStorage.setItem('language', lang);
    };

    const t = (key: string): string => {
        // @ts-ignore
        const translated = translations[language][key];
        if (translated) return translated;
        
        // Fallback to English if German translation is missing
        if (language === 'de') {
            // @ts-ignore
            return translations['en'][key] || key;
        }
        return key;
    };

    const pluralize = (count: number, singularKey: string, pluralKey: string): string => {
        const key = count === 1 ? singularKey : pluralKey;
        const translated = t(key);
        return translated.replace('{count}', count.toString());
    };

    return (
        <LanguageContext.Provider value={{ language, setLanguage, t, pluralize }}>
            {children}
        </LanguageContext.Provider>
    );
};

export const useLanguage = () => {
    const context = useContext(LanguageContext);
    if (!context) {
        throw new Error('useLanguage must be used within a LanguageProvider');
    }
    return context;
};
